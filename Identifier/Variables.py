# Assign values
length = 10       # 10 is variable and length is identifier.
width = 5         # 5  is variable and width is identifier.

# Use them in an expression
area = length * width
print(area)        # Output: 50

# Change the value of a variable
length = 20        # New value assigned to 'length'
new_area = length * width
print(new_area)    # Output: 100
