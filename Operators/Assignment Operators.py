# Basic Assignment
x = 10   # Assign 10 to x
print("x =", x)  # 10

# Add AND assign
x += 5   # x = x + 5
print("x += 5 ->", x)  # 15

# Subtract AND assign
x -= 3   # x = x - 3
print("x -= 3 ->", x)  # 12

# Multiply AND assign
x *= 2   # x = x * 2
print("x *= 2 ->", x)  # 24

# Divide AND assign
x /= 4   # x = x / 4
print("x /= 4 ->", x)  # 6.0

# Modulus AND assign
x %= 4   # x = x % 4
print("x %= 4 ->", x)  # 2.0

# Exponent AND assign
x **= 3  # x = x ** 3
print("x **= 3 ->", x)  # 8.0

# Floor Division AND assign
x //= 2  # x = x // 2
print("x //= 2 ->", x)  # 4.0
