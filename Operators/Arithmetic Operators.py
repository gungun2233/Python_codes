print("5 + 3 =", 5 + 3)      # Addition
print("5 - 3 =", 5 - 3)      # Subtraction
print("5 * 3 =", 5 * 3)      # Multiplication
print("5 / 2 =", 5 / 2)      # Division (gives float)
print("5 // 2 =", 5 // 2)    # Floor Division (integer result)
print("5 % 2 =", 5 % 2)      # Modulus (remainder)
print("2 ** 3 =", 2 ** 3)    # Exponentiation (power)

